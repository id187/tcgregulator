export function getAnimationPromotionCopy(
  elapsedDays: number,
  durationDays: number,
): readonly string[] {
  const safeDuration = Math.max(1, Math.floor(durationDays));
  const broadcastDay = Math.min(
    safeDuration,
    Math.max(1, Math.floor(elapsedDays)),
  );
  const progress = broadcastDay / safeDuration;
  const templates = progress <= 0.2
    ? ANIMATION_PROMOTION_OPENING_COPY
    : progress <= 0.8
      ? ANIMATION_PROMOTION_MIDDLE_COPY
      : ANIMATION_PROMOTION_FINALE_COPY;
  const broadcastWeek = Math.ceil(broadcastDay / 7);

  return templates.map((template) =>
    template
      .replaceAll("{broadcastDay}", String(broadcastDay))
      .replaceAll("{broadcastWeek}", String(broadcastWeek))
      .replaceAll("{durationDays}", String(safeDuration))
  );
}

